-- Proposition a relire avec l'equipe. Ne pas executer automatiquement.
-- Aucun compte ni mot de passe n'est cree par ce script.
-- Le lien entre conducteur_id et l'utilisateur reste a confirmer.

BEGIN;
SET LOCAL search_path TO public;

CREATE TABLE parking_auth_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(512) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT parking_auth_users_email_valid
        CHECK (email = btrim(email) AND email <> ''),
    CONSTRAINT parking_auth_users_display_name_valid
        CHECK (btrim(display_name) <> ''),
    CONSTRAINT parking_auth_users_password_hash_valid
        CHECK (btrim(password_hash) <> '')
);

CREATE UNIQUE INDEX parking_auth_users_email_unique
    ON parking_auth_users (lower(email));

CREATE TABLE parking_auth_user_roles (
    user_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    CONSTRAINT parking_auth_user_roles_pk PRIMARY KEY (user_id, role),
    CONSTRAINT parking_auth_user_roles_user_fk
        FOREIGN KEY (user_id) REFERENCES parking_auth_users (id) ON DELETE CASCADE,
    CONSTRAINT parking_auth_user_roles_role_valid
        CHECK (role IN ('CONDUCTEUR', 'AGENT', 'ADMIN'))
);

COMMIT;
