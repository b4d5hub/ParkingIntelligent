CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              conducteur_id BIGINT NOT NULL,
                              place_id BIGINT NOT NULL,
                              debut_prevu TIMESTAMP WITH TIME ZONE NOT NULL,
                              fin_prevue TIMESTAMP WITH TIME ZONE NOT NULL,
                              arrivee_reelle TIMESTAMP WITH TIME ZONE,
                              depart_reel TIMESTAMP WITH TIME ZONE,
                              statut VARCHAR(20) NOT NULL,
                              montant_estime NUMERIC(10, 2),
                              montant_final NUMERIC(10, 2),

                              CONSTRAINT reservation_dates_valides
                                  CHECK (fin_prevue > debut_prevu),

                              CONSTRAINT reservation_statut_valide
                                  CHECK (statut IN (
                                                    'CONFIRMED', 'IN_PROGRESS', 'COMPLETED',
                                                    'CANCELLED', 'EXPIRED'
                                      ))
);